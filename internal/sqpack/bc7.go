var bc7Weights2 = [4]int{0, 21, 43, 64}
var bc7Weights3 = [8]int{0, 9, 18, 27, 37, 46, 55, 64}
var bc7Weights4 = [16]int{0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64}

type bc7BitReader struct {
	lo  uint64
	hi  uint64
	pos int
}

func (r *bc7BitReader) read(n int) int {
	if n == 0 {
		return 0
	}
	var val uint64
	if r.pos+n <= 64 {
		val = (r.lo >> uint(r.pos)) & ((uint64(1) << uint(n)) - 1)
	} else if r.pos >= 64 {
		val = (r.hi >> uint(r.pos-64)) & ((uint64(1) << uint(n)) - 1)
	} else {
		loBits := 64 - r.pos
		hiBits := n - loBits
		loPart := r.lo >> uint(r.pos)
		hiPart := r.hi & ((uint64(1) << uint(hiBits)) - 1)
		val = loPart | (hiPart << uint(loBits))
	}
	r.pos += n
	return int(val)
}

func bc7Unquantize(val, prec int) byte {
	val <<= (8 - prec)
	return byte(val | (val >> prec))
}

func bc7Interp(e0, e1 byte, weight int) byte {
	return byte(((64-weight)*int(e0) + weight*int(e1) + 32) >> 6)
}

func bc7Weight(bits, idx int) int {
	switch bits {
	case 2:
		return bc7Weights2[idx&3]
	case 3:
		return bc7Weights3[idx&7]
	case 4:
		return bc7Weights4[idx&15]
	default:
		return 0
	}
}

func decodeBC7Block(block []byte) [16][4]byte {
	var out [16][4]byte
	r := bc7BitReader{
		lo: binary.LittleEndian.Uint64(block[0:8]),
		hi: binary.LittleEndian.Uint64(block[8:16]),
	}

	mode := 0
	for mode < 8 && r.read(1) == 0 {
		mode++
	}
	if mode >= 8 {
		return out
	}

	mi := bc7Modes[mode]
	partition := r.read(mi.partitionBits)
	rotation := r.read(mi.rotationBits)
	indexSel := r.read(mi.indexSelBits)

	numEndpoints := mi.numSubsets * 2
	var ep [6][4]int

	// 依次读取 R, G, B 端点
	for ch := 0; ch < 3; ch++ {
		for e := 0; e < numEndpoints; e++ {
			ep[e][ch] = r.read(mi.colorBits)
		}
	}
	// 读取 Alpha 端点（若有）
	if mi.alphaBits > 0 {
		for e := 0; e < numEndpoints; e++ {
			ep[e][3] = r.read(mi.alphaBits)
		}
	}

	// 读取 P-bit 并展开精度到 8-bit
	var epBytes [6][4]byte
	if mi.endpointPBits > 0 {
		for e := 0; e < numEndpoints; e++ {
			p := r.read(1)
			for ch := 0; ch < 3; ch++ {
				epBytes[e][ch] = bc7Unquantize((ep[e][ch]<<1)|p, mi.colorBits+1)
			}
			if mi.alphaBits > 0 {
				epBytes[e][3] = bc7Unquantize((ep[e][3]<<1)|p, mi.alphaBits+1)
			} else {
				epBytes[e][3] = 255
			}
		}
	} else if mi.sharedPBits > 0 {
		for s := 0; s < mi.numSubsets; s++ {
			p := r.read(1)
			for k := 0; k < 2; k++ {
				e := s*2 + k
				for ch := 0; ch < 3; ch++ {
					epBytes[e][ch] = bc7Unquantize((ep[e][ch]<<1)|p, mi.colorBits+1)
				}
				epBytes[e][3] = 255
			}
		}
	} else {
		for e := 0; e < numEndpoints; e++ {
			for ch := 0; ch < 3; ch++ {
				epBytes[e][ch] = bc7Unquantize(ep[e][ch], mi.colorBits)
			}
			if mi.alphaBits > 0 {
				epBytes[e][3] = bc7Unquantize(ep[e][3], mi.alphaBits)
			} else {
				epBytes[e][3] = 255
			}
		}
	}

	isAnchor := func(pixel int) bool {
		if pixel == 0 {
			return true
		}
		if mi.numSubsets == 2 {
			return pixel == bc7AnchorIndex2[partition]
		}
		if mi.numSubsets == 3 {
			return pixel == bc7AnchorIndex3A[partition] || pixel == bc7AnchorIndex3B[partition]
		}
		return false
	}

	var idx1 [16]int
	for i := 0; i < 16; i++ {
		bits := mi.indexBits
		if isAnchor(i) {
			bits--
		}
		idx1[i] = r.read(bits)
	}

	var idx2 [16]int
	if mi.index2Bits > 0 {
		for i := 0; i < 16; i++ {
			bits := mi.index2Bits
			if i == 0 {
				bits--
			}
			idx2[i] = r.read(bits)
		}
	}

	for i := 0; i < 16; i++ {
		subset := 0
		if mi.numSubsets == 2 {
			subset = int(bc7PartitionTable2[partition][i])
		} else if mi.numSubsets == 3 {
			subset = int(bc7PartitionTable3[partition][i])
		}
		e0 := epBytes[subset*2]
		e1 := epBytes[subset*2+1]

		var cw, aw int
		if mi.index2Bits == 0 {
			cw = bc7Weight(mi.indexBits, idx1[i])
			aw = cw
		} else if indexSel == 0 {
			cw = bc7Weight(mi.indexBits, idx1[i])
			aw = bc7Weight(mi.index2Bits, idx2[i])
		} else {
			cw = bc7Weight(mi.index2Bits, idx2[i])
			aw = bc7Weight(mi.indexBits, idx1[i])
		}

		pix := [4]byte{
			bc7Interp(e0[0], e1[0], cw),
			bc7Interp(e0[1], e1[1], cw),
			bc7Interp(e0[2], e1[2], cw),
			bc7Interp(e0[3], e1[3], aw),
		}

		// 处理通道旋转（Mode 4 / Mode 5）
		switch rotation {
		case 1:
			pix[0], pix[3] = pix[3], pix[0]
		case 2:
			pix[1], pix[3] = pix[3], pix[1]
		case 3:
			pix[2], pix[3] = pix[3], pix[2]
		}

		out[i] = pix
	}

	return out
}

func decodeBC7(src, dst []byte, w, h int) {
	bw := (w + 3) / 4
	bh := (h + 3) / 4
	pos := 0
	for by := 0; by < bh; by++ {
		for bx := 0; bx < bw; bx++ {
			if pos+16 > len(src) {
				return
			}
			pixels := decodeBC7Block(src[pos : pos+16])
			pos += 16
			for py := 0; py < 4; py++ {
				y := by*4 + py
				if y >= h {
					continue
				}
				for px := 0; px < 4; px++ {
					x := bx*4 + px
					if x >= w {
						continue
					}
					di := (y*w + x) * 4
					copy(dst[di:di+4], pixels[py*4+px][:])
				}
			}
		}
	}
}
